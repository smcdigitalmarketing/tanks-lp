/**
 * Writes docs/asset-manifest.md from app/data/catalog.json and reviews.json,
 * so the manifest always matches what `npm run store:port` downloaded.
 *
 *   npm run assets:manifest
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(
  readFileSync(join(root, "app/data/catalog.json"), "utf8"),
);
const reviews = JSON.parse(
  readFileSync(join(root, "app/data/reviews.json"), "utf8"),
);

type Asset = {
  name: string;
  file: string;
  source: string;
  width: number;
  height: number;
  origin: string;
  use: string;
  flags: string[];
};

const FLAGS: Record<string, string> = {
  rights:
    "Competitor's asset. Usage rights not cleared: approval or replacement needed before production.",
  "ai-likely":
    "Filename suggests AI generation (freepik, magnific, nano banana, ChatGPT). Check provenance.",
  "low-res":
    "Below 1600 px. Gallery exports at 1600 px are upscaled and slightly soft.",
  "not-square": "Not square; cropped to fit square slots.",
  "before-after":
    "Before/after style image. Implies a body-shape result; only used (if at all) with construction-only labels.",
  "cross-store":
    "Served from a different Shopify store (files/1/0962/4692/3588), origin unclear.",
  "text-baked-in":
    "Words are part of the image; not usable in the gallery (all text must be HTML).",
  conflicting: "Its content contradicts other source pages.",
  "real-person":
    "A real customer's photo from a public review. Needs consent before any production use.",
  "unverified-person":
    "Shows a person the source presents as its founder; identity unverified.",
};

const assets: Asset[] = catalog.assets;
const row = (a: Asset) =>
  `| \`${a.name}\` | ${a.file === "(not downloaded)" ? "not downloaded" : `\`${a.file}\``} | ${a.width ? `${a.width}×${a.height}` : "–"} | ${a.use} | ${a.flags.map((f) => `\`${f}\``).join(" ")} | [source](${a.source}) |`;
const table = (list: Asset[]) =>
  [
    "| Name | File | Size | Used for | Flags | Source |",
    "|---|---|---|---|---|---|",
    ...list.map(row),
  ].join("\n");

const used = assets.filter(
  (a) => a.file !== "(not downloaded)" && !a.use.startsWith("Not used"),
);
const unused = assets.filter(
  (a) => a.file === "(not downloaded)" || a.use.startsWith("Not used"),
);

const md = `# Asset manifest

Generated by \`npm run assets:manifest\` from \`app/data/catalog.json\` and \`app/data/reviews.json\` (ported ${catalog.portedAt} from ${catalog.source}). Don't edit by hand.

**Nothing in this list is cleared for production.** Every file comes from the competitor's public store and is used here only for internal evaluation. The Hallie store uses them in fixed slots on every page and gallery slide.

- ${assets.length} assets recorded: ${used.length} in use, ${unused.length} recorded but not used.
- Photos are saved at native size as webp (\`app/assets/store/\`), never upscaled on disk. The 1600 × 1600 gallery exports in \`public/gallery/\` are rendered by \`npm run gallery:export\` and contain no competitor text.
- Product images were fetched from the public product JSON (\`/products/<handle>.json\`); page images and the video from public CDN URLs in the page HTML; review photos from Judge.me's public review widget. No protected endpoints.

## Flags

| Flag | Meaning |
|---|---|
${Object.entries(FLAGS)
  .map(([k, v]) => `| \`${k}\` | ${v} |`)
  .join("\n")}

## In use

${table(used)}

## Recorded, not used

${table(unused)}

## Reviews

${reviews.items.length} reviews copied word for word from ${reviews.source} (fetched ${reviews.fetchedAt}). All are shown with a "Competitor review" flag as placeholders. Names are the reviewers' display names on Judge.me.

| Reviewer | Rating | Date | Photo | Judge.me id |
|---|---|---|---|---|
${reviews.items.map((r: { name: string; rating: number; date: string; photo: string | null; id: string }) => `| ${r.name} | ${r.rating}★ | ${r.date} | ${r.photo ? `\`${r.photo}\`` : "–"} | \`${r.id}\` |`).join("\n")}

Selection rule: from the newest ${reviews.recentSample.total} reviews, 4–5★ reviews clearly about this tank, excluding medical claims (surgery, cancer, spinal pain), weight-loss or "slimming" wording, and quotes that name the competitor's brand.
`;

writeFileSync(join(root, "docs/asset-manifest.md"), md);
console.log(
  `docs/asset-manifest.md: ${assets.length} assets, ${reviews.items.length} reviews`,
);
